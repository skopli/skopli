export function pseudolocalize(text: string): string {
  const parts = text.split(/(\{[^}]+\})/);
  const body = parts
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/[A-Za-z]/g, (c) => accents[c] ?? c)))
    .join("");
  const padding = "\u00b7".repeat(Math.ceil(text.replace(/\{[^}]+\}/g, "").length * 0.3));
  return `[${body}${padding}]`;
}
